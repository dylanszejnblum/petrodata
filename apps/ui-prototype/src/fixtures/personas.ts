/* PERSONALIDADES — quién dirige cada empresa del ranking, con el índice.

   Sale de cruzar CEOS/data/state.json —el pipeline que busca y confirma al CEO
   actual de las 50 primeras empresas del sitio— con COMPANIES de este mismo
   repo. Cruzan 48 de 50 y cubren el 97,6% del valor de la producción del país.

   NO hay ninguna métrica de la PERSONA en el dato: nombre, cargo y fuente es
   todo lo que trae el pipeline. El índice es de la EMPRESA, atribuido a quien
   la dirige, y la página lo dice. Cualquier otra lectura sería inventar.

   `confirmado` viene del pipeline y sólo es true en 28 de 48: el resto son
   cargos que una sola fuente sugiere y nadie verificó. La lista lo muestra en
   vez de esconderlo — publicar «CEO de X» sobre un dato sin confirmar es
   exactamente lo que no conviene en una página sobre personas con nombre. */

export type Persona = {
  /** el slug de la EMPRESA, no de la persona: es la clave del cruce */
  slug: string
  nombre: string
  cargo: string
  empresa: string
  /** true = el pipeline verificó el cargo contra más de una fuente */
  confirmado: boolean
  /** la fuente del cargo, para poder citarla en la ficha */
  fuente: string
  /** FECHA DE LA FUENTE, no de la asunción. Es cuándo se verificó el cargo, y
      en 25 de las 48 sigue siendo literalmente el `as_of` del pipeline. No
      sirve para calcular antigüedad y no viaja al navegador: ordena la cola de
      verificación y nada más. */
  desde: string
  /** DESDE CUÁNDO OCUPA EL CARGO. Es otro dato y por eso es otro campo: mezclar
      los dos fue lo que hizo que la ficha mostrara la fecha de una nota de
      prensa como si fuera la asunción —Marín salía con 2026 cuando asumió en
      diciembre de 2023, y Mindlin con 2026 cuando está en el directorio desde
      2006—.

      Acepta año, año-mes o fecha completa, según lo que diga la fuente: casi
      ninguna da el día. Va sólo si está verificado; sin dato, la ficha omite el
      renglón, igual que hace con la bio. */
  enElCargoDesde?: string
  /** UNA O DOS FRASES, y sólo si salen de una fuente que se leyó.

      NO hay biografías en el pipeline: `state.json` trae nombre, cargo y
      fuente, nada más. Las que están acá se escribieron con lo que apareció en
      las notas y las páginas oficiales que se usaron para verificar el cargo
      —formación, de dónde viene, desde cuándo—, así que cada una tiene atrás la
      misma fuente que la fila.

      Las que faltan faltan a propósito. Rellenar cuarenta y ocho con prosa
      plausible es exactamente el error que costó doce caras inventadas. */
  bio?: string
  /* ── los insumos del índice, todos públicos ─────────────────────────── */
  pctValor: number
  pctNacional: number
  pozos: number
  /* ── el índice y sus tres componentes, ya normalizados 0-100 ────────── */
  indice: number
  escala: number
  rinde: number
  prima: number
}

/* El índice: escala 60% · rendimiento 25% · prima 15%.

   El rendimiento se divide por (pozos + 500) y no por pozos. Sin ese piso,
   GeoPark entraba séptima con el 0,1% del valor porque opera nueve pozos —el
   artefacto del denominador chico— y un índice que pone a una empresa de nueve
   pozos arriba de Pampa pierde toda credibilidad ante la gente que se supone
   que tiene que impresionar. 500 es tres veces la mediana de pozos; con ese
   piso no queda ningún intruso por debajo del 0,5% del valor en el top 10. */
/* LO QUE VIAJA AL NAVEGADOR, y es a propósito que sea menos que `Persona`.

   La ponderación del índice no se publica. Pero `ListaPersonas` es un
   componente de cliente, así que todo lo que reciba por props se serializa en
   el HTML: pasándole `Persona[]` entero, cada fila salía con sus tres
   componentes ya normalizados —escala, rinde, prima— al lado del índice.
   Cuarenta y ocho filas son cuarenta y ocho ecuaciones con tres incógnitas:
   los pesos se despejan por mínimos cuadrados en un minuto. El algoritmo era
   secreto en la prosa y público en el `view-source`.

   Así que la página manda esta proyección y nada más. Los insumos y los
   componentes se quedan del lado del servidor, que es donde se calcula. */
/* `confirmado` YA NO VIAJA (pedido de Mariano, 2026-09-01: «las otras van, pero
   sin el chip de sin confirmar, a lo sumo que la empresa nos contacte»). El
   campo se queda en `Persona` porque el dato sigue siendo cierto y es lo que
   ordena la cola de verificación; lo que se saca es la marca en la fila.

   Se saca de la proyección y no del render por la misma razón que los pesos
   del índice: lo que no se muestra tampoco tiene por qué serializarse en el
   HTML. Un `confirmado: false` en el view-source dice exactamente lo que el
   chip decía.

   `enElCargoDesde` y `bio` SÍ viajan, porque la ficha que se abre al tocar la
   fila los muestra. Son datos del CARGO y de la persona; no son insumos del índice, así
   que no dicen nada sobre la ponderación.

   `fuente` y `desde` NO viajan. Los dos describen la VERIFICACIÓN y no a la
   persona: uno es el link que respalda el cargo y el otro la fecha en que se
   comprobó. Un campo que no se pinta no se serializa, y además un fuente vacío
   en el view-source dice «esta fila no está confirmada», que es exactamente lo
   que se sacó de la vista.

   Lo que sigue sin viajar es lo mismo de antes: pctValor, pctNacional, pozos,
   escala, rinde y prima. Los tres primeros son los insumos del índice —el pie
   de la card los nombra— y publicarlos AL LADO del índice, cuarenta y ocho
   veces, es publicar cuarenta y ocho ecuaciones con tres incógnitas. La ficha
   se queda sin cifras de la empresa a propósito: para eso está /v2/empresas. */
export type PersonaFila = Pick<
  Persona,
  'slug' | 'nombre' | 'cargo' | 'empresa' | 'indice' | 'enElCargoDesde' | 'bio'
> & {
  /** si el archivo de la cara existe. Lo resuelve el SERVIDOR, ver page.tsx. */
  foto: boolean
}

export function aFila(p: Persona, foto = false): PersonaFila {
  return {
    foto,
    slug: p.slug,
    nombre: p.nombre,
    cargo: p.cargo,
    empresa: p.empresa,
    indice: p.indice,
    enElCargoDesde: p.enElCargoDesde,
    bio: p.bio,
  }
}

